function parseArgs(argv) {
  const args = {
    cd: null,
    exec: [],
    execIn: [],
    timeout: DEFAULT_TIMEOUT_S,
    envMode: 'filtered',
    envPassthrough: [],
    out: null,
    checkStale: null,
    base: null,
    compact: false,
    tail: DEFAULT_TAIL_LINES,
    logDir: null,
    repos: [],
    fetch: false,
    watchFiles: [],
    sourceSnapshots: [],
    host: null,
    runDir: null,
    seats: null,
    matchedTools: null,
    probeDispatch: false,
    yesPaid: false,
    allowTrial: false,
    skipCodexDoctor: false,
    probeClaudeSession: false,
    probeReach: false,
    keepTargetCopy: false,
    reviewRules: null,
    reviewRulesOnly: [],
  };
  for (let i = 0; i < argv.length; i++) {
    const tok = argv[i];
    const takeValue = () => {
      const v = argv[++i];
      if (v === undefined || v.startsWith('--')) throw new RelayError(`${tok} requires a value`);
      return v;
    };
    if (tok === '--cd') args.cd = takeValue();
    else if (tok === '--exec') args.exec.push(takeValue());
    else if (tok === '--exec-file') {
      args.exec.push(...readCommandFile(takeValue(), tok));
    } else if (tok === '--exec-in') {
      const dir = takeValue();
      args.execIn.push({ dir, command: takeValue() });
    } else if (tok === '--exec-in-file') {
      const dir = takeValue();
      for (const command of readCommandFile(takeValue(), tok)) args.execIn.push({ dir, command });
    } else if (tok === '--timeout') {
      const v = takeValue();
      if (!/^[0-9]+$/.test(v)) throw new RelayError('--timeout must be a whole number of seconds, 0 for unlimited');
      args.timeout = Number(v);
    } else if (tok === '--env-mode') args.envMode = takeValue();
    else if (tok === '--env-passthrough') args.envPassthrough = takeValue().split(',').map((s) => s.trim()).filter(Boolean);
    else if (tok === '--out') args.out = takeValue();
    else if (tok === '--check-stale') args.checkStale = takeValue();
    else if (tok === '--base') args.base = takeValue();
    else if (tok === '--compact') args.compact = true;
    else if (tok === '--fail-on-command-error') args.failOnCommandError = true;
    else if (tok === '--tail') {
      const v = takeValue();
      if (!/^[0-9]+$/.test(v)) throw new RelayError('--tail must be a whole number of lines');
      args.tail = Number(v);
    } else if (tok === '--log-dir') args.logDir = takeValue();
    else if (tok === '--repo') args.repos.push(takeValue());
    else if (tok === '--source-snapshot') {
      const v = takeValue();
      // <dir>=<repo>@<ref>: the last "@" splits repo from ref, the first "=" splits the folder off.
      const m = /^(.+?)=(.+)@([^@\s]+)$/.exec(v);
      if (!m || m[2].trim() === '') throw new RelayError(`--source-snapshot "${v}" must look like <folder>=<repo>@<commit or tag>, with no spaces in the ref, for example exports/svc=org/svc@b45981e`);
      args.sourceSnapshots.push({ dir: m[1], repo: m[2], ref: m[3] });
    }
    else if (tok === '--host') args.host = takeValue();
    else if (tok === '--run-dir') args.runDir = takeValue();
    else if (tok === '--seats') args.seats = takeValue();
    else if (tok === '--matched-tools') args.matchedTools = takeValue();
    else if (tok === '--probe-dispatch') args.probeDispatch = true;
    else if (tok === '--yes-paid') args.yesPaid = true;
    else if (tok === '--allow-trial') args.allowTrial = true;
    else if (tok === '--skip-codex-doctor') args.skipCodexDoctor = true;
    else if (tok === '--probe-claude-session') args.probeClaudeSession = true;
    else if (tok === '--probe-reach') args.probeReach = true;
    else if (tok === '--keep-target-copy') args.keepTargetCopy = true;
    else if (tok === '--review-rules') {
      args.reviewRules = takeValue();
      if (!['head', 'worktree'].includes(args.reviewRules)) throw new RelayError(`--review-rules must be head or worktree, got "${args.reviewRules}"`);
    }
    else if (tok === '--review-rules-only') args.reviewRulesOnly.push(takeValue());
    else if (tok === '--fetch') args.fetch = true;
    else if (tok === '--watch-file') args.watchFiles.push(takeValue());
    else if (tok === '-h' || tok === '--help') printUsageAndExit(0);
    else throw new RelayError(`unrecognized argument: ${tok}`);
  }
  if (!args.cd) throw new RelayError('--cd <path> is required');
  if (args.host === null) {
    const stray = ['runDir', 'seats', 'matchedTools', 'reviewRules'].filter((k) => args[k] !== null).concat(args.reviewRulesOnly.length > 0 ? ['reviewRulesOnly'] : [],args.probeDispatch ? ['probeDispatch'] : [], args.yesPaid ? ['yesPaid'] : [], args.allowTrial ? ['allowTrial'] : [], args.skipCodexDoctor ? ['skipCodexDoctor'] : [], args.probeClaudeSession ? ['probeClaudeSession'] : [], args.probeReach ? ['probeReach'] : [], args.keepTargetCopy ? ['keepTargetCopy'] : []);
    if (stray.length > 0) throw new RelayError('--run-dir, --seats, --matched-tools, --review-rules, --review-rules-only, --probe-dispatch, --probe-claude-session, --probe-reach, --keep-target-copy, --yes-paid, --allow-trial and --skip-codex-doctor are only accepted with --host');
  } else {
    if (args.execIn.length > 0 || args.exec.length > 0) throw new RelayError('--exec, --exec-file, --exec-in and --exec-in-file are not used with --host; run them in a separate preflight call without --host');
    if (args.base) throw new RelayError('--base is not used with --host; give it to the evidence preflight (without --host)');
    if (!HOSTS.includes(args.host)) throw new RelayError(`--host must be one of ${HOSTS.join(', ')}, got "${args.host}"`);
    if (!args.runDir || (!args.seats && !args.probeReach)) throw new RelayError('--host requires --run-dir and --seats');
  }
  if (args.compact && !args.logDir) {
    if (!args.out) throw new RelayError('--compact needs --log-dir (or --out, which defaults it to "<--out>.logs")');
    args.logDir = `${args.out}.logs`;
  }
  if (args.envMode !== 'filtered' && args.envMode !== 'inherit') {
    throw new RelayError('--env-mode must be "filtered" or "inherit"');
  }
  for (const name of args.envPassthrough) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
      throw new RelayError(`--env-passthrough: "${name}" is not a valid environment variable name`);
    }
  }
  return args;
}

// git is invoked directly (structured argv, shell:false, no shell metachar
// risk from a repo path) -- this is NOT the Tier 2 --exec path, which needs
// a real shell to interpret an arbitrary caller-supplied command string; see
// runWithTimeout below for that.
function runCapture(cmd, args, cwd, env = process.env) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { windowsHide: true, cwd, env, shell: false });
    let stdout = Buffer.alloc(0);
    let stderr = Buffer.alloc(0);
    child.stdout.on('data', (d) => { stdout = Buffer.concat([stdout, d]); });
    child.stderr.on('data', (d) => { stderr = Buffer.concat([stderr, d]); });
    child.on('error', reject);
    child.on('close', (code) => resolve({ code, stdout, stderr }));
  });
}

async function isGitRepo(cwd) {
  const result = await runCapture('git', ['rev-parse', '--is-inside-work-tree'], cwd, { ...process.env, ...GIT_C_LOCALE }).catch((err) => {
    throw new RelayError(err.code === 'ENOENT' ? 'git is required and was not found on PATH; install git (or put it on PATH) and run preflight again' : `git could not run: ${err.message}`);
  });
  try {
    return gitRepoFromProbe({ code: result.code, stdout: result.stdout.toString('utf8'), stderr: result.stderr.toString('utf8') }, cwd);
  } catch (err) {
    throw new RelayError(err.message);
  }
}

// Tier 1: pure repository-state inspection, no execution of anything the
// target repo defines. Runs unconditionally, no opt-in required.
// inventory: an already computed hashInventory(cd) for a plain folder, so run() hashes it once.
async function runTier1(cd, inventory = null, base = null) {
  const gitTracked = await isGitRepo(cd);
  if (!gitTracked) {
    if (base) throw new RelayError(`--base ${base} needs a git repository; "${cd}" is not one`);
    inventory ??= await hashInventory(cd);
    return {
      gitRepo: false,
      fileCount: Object.keys(inventory.files).length,
      note: `"${cd}" is not a git repository; diff/status evidence is unavailable, and snapshotHash is a content-hash inventory of every file (skipping .git/ and node_modules/)`,
    };
  }
  // git diff HEAD (not bare `git diff`, working-tree-vs-index only) so
  // STAGED changes are included too -- a review target commonly has staged
  // work, and a bare `git diff` would silently omit it. changedFiles/
  // fileStats include untracked files as well, matching computeSnapshotHash's
  // own coverage below (HEAD diff + untracked content). --relative on both
  // diff calls makes their paths cd-relative, matching git status/ls-files
  // (already cwd-relative) and the stat(path.join(cd, rel)) calls below --
  // without it, a cd pointed at a subdirectory would produce root-relative
  // diff paths that never match, silently dropping every tracked change
  // from fileStats.
  // git status --porcelain is not cwd-relative: "-- ." keeps it to --cd, and its paths keep the repository-root prefix
  // (gitPrefix, from rev-parse --show-prefix), which summaryLine strips to match changedFiles.
  // --base: the diff runs from that commit, so work already committed is listed too.
  let from = 'HEAD';
  if (base) {
    const r = await runCapture('git', ['rev-parse', '--verify', '--quiet', `${base}^{commit}`], cd);
    if (r.code !== 0) throw new RelayError(`--base ${base} is not a commit in ${cd}`);
    from = r.stdout.toString('utf8').trim();
  }
  const [diff, status, nameOnly, untrackedNames, prefix] = await gitOutAll([
    [...GIT_PLAIN, 'diff', ...DIFF_PLAIN, '--no-renames', '--relative', from],
    [...GIT_PLAIN, 'status', '--porcelain', '--', '.'],
    [...GIT_PLAIN, 'diff', ...DIFF_PLAIN, '--no-renames', '--relative', from, '--name-only', '-z'],
    ['ls-files', '--others', '--exclude-standard', '-z'],
    ['rev-parse', '--show-prefix'],
  ], cd);
  // -z: a file name with a non-ASCII character or a newline comes back as written, not quoted.
  const listed = new Map([...gitNames(nameOnly.stdout), ...gitNames(untrackedNames.stdout)].map((e) => [entryKey(e), e]));
  const changedFiles = [...listed.keys()];
  const fileStats = {};
  for (const rel of changedFiles) {
    try {
      const s = await stat(entryPath(cd, listed.get(rel)));
      fileStats[rel] = { sizeBytes: s.size, mtime: s.mtime.toISOString() };
    } catch {
      // File deleted in the working tree relative to the index -- no stat
      // available; omit rather than fabricate a size/mtime for a path that
      // no longer exists.
    }
  }
  return {
    gitRepo: true,
    ...(base ? { base: from } : {}),
    diff: diff.stdout.toString('utf8'),
    status: status.stdout.toString('utf8'),
    ...(prefix.stdout.toString('utf8').trim() ? { gitPrefix: prefix.stdout.toString('utf8').trim() } : {}),
    changedFiles,
    fileStats,
  };
}

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

// A git call whose output feeds a snapshot hash, a fingerprint or the evidence: a failure (a bad diff setting in the
// user's config, a broken index) must stop preflight, or an empty output would hash two different states the same.
function gitChecked(res, args, cd) {
  if (res.code !== 0) {
    // git's reason is its "fatal:" line; usage text can follow it.
    const lines = res.stderr.toString('utf8').trim().split(/\r?\n/);
    const reason = lines.find((l) => /^fatal:/.test(l)) ?? lines.slice(-1)[0] ?? '';
    const hint = /ambiguous argument 'HEAD'|unknown revision/.test(reason) ? ' (no commits yet?)' : '';
    throw new RelayError(`git ${args.filter((a) => !a.startsWith('-c') && !a.includes('=')).join(' ')} failed in "${cd}" (exit ${res.code}): ${reason}${hint}`);
  }
  return res;
}

async function gitOut(args, cd) {
  return gitChecked(await runCapture('git', args, cd), args, cd);
}

// Several git calls at once; every one is awaited before a failure is reported, so none is left running.
async function gitOutAll(argsList, cd) {
  const results = await Promise.all(argsList.map((args) => runCapture('git', args, cd)));
  return results.map((res, i) => gitChecked(res, argsList[i], cd));
}

// Scoped to --cd: the committed tree of that folder, its binary diff against HEAD (so a binary
// change is distinguishable), and a content hash per untracked file (so a created file counts).
// A commit or edit elsewhere in a monorepo does not make this target's evidence stale.
async function computeSnapshotHash(cd, inventory = null) {
  if (!(await isGitRepo(cd))) return (inventory ?? (await hashInventory(cd))).snapshotHash;
  const headRes = await runCapture('git', ['rev-parse', 'HEAD'], cd);
  if (headRes.code !== 0) {
    throw new RelayError(`could not resolve HEAD in "${cd}" (not a git repo, or no commits yet)`);
  }
  const prefix = (await gitOut(['rev-parse', '--show-prefix'], cd)).stdout.toString('utf8').replace(/\r?\n$/, '');
  const treeRes = await runCapture('git', ['rev-parse', `HEAD:${prefix}`], cd);
  // A folder that exists only in the working tree has no committed tree yet.
  const treeId = treeRes.code === 0 ? treeRes.stdout.toString('utf8').trim() : 'no-committed-tree';
  const diffRes = await gitOut([...GIT_PLAIN, 'diff', ...DIFF_PLAIN, 'HEAD', '--binary', '--relative', '--', '.'], cd);
  const untrackedRes = await gitOut(['ls-files', '--others', '--exclude-standard', '-z'], cd);
  const untrackedEntries = gitNames(untrackedRes.stdout).filter((e) => !e.text.endsWith('/')).sort((a, b) => (a.text < b.text ? -1 : a.text > b.text ? 1 : 0));

  const hash = createHash('sha256');
  hash.update(treeId);
  hash.update('\n');
  hash.update(diffRes.stdout);
  for (const entry of untrackedEntries) {
    hash.update('\n');
    hash.update(nameBytes(entry));
    hash.update(':');
    hash.update(await entrySha256(entryPath(cd, entry)));
  }
  return hash.digest('hex');
}

// Tier 2's --exec command is an arbitrary caller-supplied shell command
// string (e.g. "npm test", "pytest -q && echo done"), so this genuinely
// needs `shell: true` on both platforms to be interpreted at all -- unlike
// the dispatchers' spawnCli, which only ever
// invokes a known executable (claude/codex) with structured argv and
// therefore uses shell:true JUST for win32's .cmd-shim resolution. killTree
// (from spawn-utils.mjs) still applies for the timeout-kill path: on win32
// it uses taskkill /T against the whole process tree (the same reason
// the dispatchers need it -- a plain child.kill()
// only terminates cmd.exe, orphaning the real process underneath).
// spawnFn/platform overridable so tests can assert detached:true on the POSIX branch without
// needing to actually run on POSIX (same seam spawn-utils.mjs's spawnCli uses).
// A child in its own process group (spawnCli, detached:true) is not reached by a Ctrl-C or kill of preflight: on
// SIGINT, SIGTERM or SIGHUP this kills the child's tree, runs onStop, then exits 128 + the signal number.
function stopOnSignal(child, { proc = process, exit = (code) => process.exit(code), onStop = () => {} } = {}) {
  const guard = { stopping: false };
  const handlers = {};
  for (const [sig, code] of Object.entries({ SIGINT: 130, SIGTERM: 143, SIGHUP: 129 })) {
    // A second signal (Ctrl-C pressed again) must not reach Node's default handler, which would exit before the kill ends.
    handlers[sig] = () => {
      if (guard.stopping) return;
      guard.stopping = true;
      killTree(child, { waitForGroup: true })
        .then(onStop)
        .catch((err) => process.stderr.write(`preflight: cleanup after ${sig} failed: ${err.message}\n`))
        .finally(() => exit(code));
    };
    proc.on(sig, handlers[sig]);
  }
  guard.uninstall = () => { for (const [sig, handler] of Object.entries(handlers)) proc.off(sig, handler); };
  return guard;
}

// Windows has no process group to kill: a background process the command started (a server, a watcher) outlives the shell.
// Processes whose parent chain starts at the shell's pid and that were created after it started are stopped with their trees;
// the creation time keeps a reused pid from matching. Returns the pids stopped.
export function stopLeftovers(rootPid, startMs, { run = spawnSync, log = (m) => process.stderr.write(m) } = {}) {
  const sys = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32');
  // conhost.exe is the console Windows attaches to the shell; it ends with it and is not the command's.
  const query = 'Get-CimInstance Win32_Process | Where-Object { $_.Name -ne "conhost.exe" } | ForEach-Object { "$($_.ProcessId) $($_.ParentProcessId) $([DateTimeOffset]::new($_.CreationDate).ToUnixTimeMilliseconds())" }';
  const listed = run(path.join(sys, 'WindowsPowerShell', 'v1.0', 'powershell.exe'), ['-NoProfile', '-NonInteractive', '-Command', query], { encoding: 'utf8', windowsHide: true, timeout: 30000 });
  if (listed.status !== 0) {
    log(`preflight: WARNING: could not list processes to stop what the command left running: ${(listed.stderr || listed.error?.message || '').trim()}\n`);
    return [];
  }
  const procs = String(listed.stdout).split(/\r?\n/).map((l) => l.trim().split(/\s+/).map(Number)).filter((p) => p.length === 3 && p.every(Number.isFinite));
  const tree = new Set([rootPid]);
  const top = [];
  for (let grew = true; grew;) {
    grew = false;
    for (const [pid, ppid, created] of procs) {
      if (!tree.has(pid) && tree.has(ppid) && created >= startMs - 1000) {
        tree.add(pid);
        if (ppid === rootPid) top.push(pid);
        grew = true;
      }
    }
  }
  for (const pid of top) run(path.join(sys, 'taskkill.exe'), ['/pid', String(pid), '/T', '/F'], { windowsHide: true, timeout: 30000 });
  if (top.length > 0) log(`preflight: WARNING: the command left ${top.length} process(es) running (pid ${top.join(', ')}); they were stopped. An --exec command must not leave a background process.\n`);
  return top;
}

// How runWithTimeout starts the command: on Windows through the job wrapper (report file in a new temp folder).
function execSpawn(command, { cd, env, platform, spawnFn }) {
  if (platform !== 'win32' || spawnFn !== spawn) {
    // detached:true makes the shell the leader of its own POSIX process group, which is what
    // lets killTree's process.kill(-pid) below reach the whole tree instead of failing ESRCH
    // against a group the child was never actually the leader of.
    return { child: spawnFn(command, { windowsHide: true, cwd: cd, env, shell: true, detached: platform !== 'win32' }), report: null };
  }
  return jobSpawn(command, { cwd: cd, env });
}

// The leftover pids the job wrapper stopped, or null when it could not use a job (then the parent-chain scan runs instead).
export function jobLeftovers(report, { log = (m) => process.stderr.write(m) } = {}) {
  const read = readJobReport(report);
  if (read.unreadable) {
    log(`preflight: WARNING: the job report ${report} could not be read (${read.unreadable}); scanning for leftover processes instead\n`);
    return null;
  }
  if (read.refused !== undefined) {
    log(`preflight: WARNING: the command could not run in a job object (${read.refused}); scanning for leftover processes instead\n`);
    return null;
  }
  return read.left;
}

// A process that left the command's process group (setsid) or job can hold its output open after the command exits.
function closeGraceMs(env = process.env) {
  return Number(env.REVIEW_CLOSE_GRACE_MS) || 2000;
}

function runWithTimeout(command, { cd, env, timeout }, { spawnFn = spawn, platform = process.platform, proc = process, exit = (code) => process.exit(code), kill: killFn = (pid, sig) => process.kill(pid, sig) } = {}) {
  const startMs = Date.now();
  return new Promise((resolve, reject) => {
    // Linux and macOS: every process the command starts inherits this id, so one that left its process group is still found.
    const runId = randomUUID();
    const { child, report, dir } = execSpawn(command, { cd, env: { ...(env ?? process.env), REVIEW_SEAT_RUN_ID: runId }, platform, spawnFn });
    // Linux and macOS: what the command left in its process group is killed when it exits; say so, as on Windows.
    let groupStopped = false;
    killGroupOnExit(child, { platform, kill: killFn, onKilled: () => { groupStopped = true; } });
    let stdout = '';
    let stderr = '';
    let settled = false;
    // Settled only after exit (which returns only in tests): the next --exec command must not start meanwhile.
    // Linux and macOS: what the command left running outside its group, found by the run id, after a timeout or a stop signal too.
    const sweepMarked = () => {
      const marked = stopMarkedProcesses(runId, { platform, kill: killFn });
      if (marked.length > 0) process.stderr.write(`preflight: WARNING: the command left ${marked.length} process(es) running outside its process group (pid ${marked.join(', ')}); they were stopped. An --exec command must not leave a background process.\n`);
      return marked;
    };
    const guard = stopOnSignal(child, {
      proc,
      onStop: () => { sweepMarked(); },
      exit: (code) => {
        exit(code);
        guard.uninstall();
        if (settled) return;
        settled = true;
        resolve({ code: null, stdout, stderr, timedOut: false, interrupted: true });
      },
    });
    const uninstall = guard.uninstall;
    let timer = null;
    // Set BEFORE calling killTree, not inside its .finally(): killTree's own
    // taskkill (win32) or SIGTERM/SIGKILL (POSIX) terminating the child fires
    // this same promise's 'close' event, which races against killTree's own
    // resolution. Flipping timedOut here first means 'close' below always
    // sees timedOut:true once the timer has fired, regardless of which
    // callback's resolve() actually wins that race.
    let timedOut = false;
    if (timeout) {
      timer = setTimeout(() => {
        timedOut = true;
        killTree(child, { waitForGroup: true }).finally(() => {
          const marked = sweepMarked();
          uninstall();
          if (settled) return;
          settled = true;
          resolve({ code: null, stdout, stderr, timedOut: true, ...(marked.length > 0 ? { leftoversStopped: marked } : {}) });
        });
      }, timeout * 1000);
    }
    // On the shell's exit, not on close: a leftover process holds the output pipes open, so close waits until it ends.
    let leftovers = [];
    let held = null;
    child.once('exit', (code) => {
      if (report && !timedOut && !guard.stopping) {
        const stopped = jobLeftovers(report);
        if (stopped === null) leftovers = child.pid ? stopLeftovers(child.pid, startMs) : [];
        else if ((leftovers = stopped).length > 0) process.stderr.write(`preflight: WARNING: the command left ${stopped.length} process(es) running (pid ${stopped.join(', ')}); they were stopped. An --exec command must not leave a background process.\n`);
      }
      if (groupStopped && !timedOut && !guard.stopping) process.stderr.write('preflight: WARNING: the command left process(es) running in its process group; they were stopped. An --exec command must not leave a background process.\n');
      if (!timedOut && !guard.stopping) {
        const marked = stopMarkedProcesses(runId, { platform, kill: killFn }).filter((p) => !leftovers.includes(p));
        if (marked.length > 0) {
          leftovers = [...leftovers, ...marked];
          process.stderr.write(`preflight: WARNING: the command left ${marked.length} process(es) running outside its process group (pid ${marked.join(', ')}); they were stopped. An --exec command must not leave a background process.\n`);
        }
      }
      // After a timeout or a stop signal the wrapper is killed: closing its job stops what the command left, unless there
      // was no job (the wrapper writes that when it starts), which is said here.
      if (report && (timedOut || guard.stopping)) {
        const read = readJobReport(report);
        if (read.refused !== undefined) process.stderr.write(`preflight: WARNING: the command could not run in a job object (${read.refused}); a process it started may still be running\n`);
      }
      if (dir) rmSync(dir, { recursive: true, force: true });
      // Its output should close now; a process that left the group or job and still holds it would stall the run until the timeout.
      if (!timedOut && !guard.stopping) {
        // It exited in time: a timeout from here on would kill a pid that may belong to another process by now.
        if (timer) clearTimeout(timer);
        held = setTimeout(() => {
          if (settled || timedOut || guard.stopping) return;
          settled = true;
          if (timer) clearTimeout(timer);
          uninstall();
          child.stdout.destroy();
          child.stderr.destroy();
          process.stderr.write('preflight: WARNING: the command exited, but a process it started still holds its output open and was not stopped (it left the command\'s process group or job); stop it yourself. An --exec command must not leave a background process.\n');
          resolve({ code, stdout, stderr, timedOut: false, outputHeldOpen: true, ...(groupStopped ? { leftoverGroupStopped: true } : {}), ...(leftovers.length > 0 ? { leftoversStopped: leftovers } : {}) });
        }, closeGraceMs());
      }
    });
    child.stdout.on('data', (d) => { stdout += d.toString('utf8'); });
    child.stderr.on('data', (d) => { stderr += d.toString('utf8'); });
    child.on('error', (err) => {
      if (timer) clearTimeout(timer);
      uninstall();
      if (settled) return;
      settled = true;
      reject(err);
    });
    child.on('close', (code) => {
      if (timer) clearTimeout(timer);
      if (held) clearTimeout(held);
      // After a timeout the timer's kill resolves this, once the whole group is gone; after a stop signal, exit does.
      if (timedOut || guard.stopping) return;
      uninstall();
      if (settled) return;
      settled = true;
      resolve({ code: timedOut ? null : code, stdout, stderr, timedOut, ...(groupStopped ? { leftoverGroupStopped: true } : {}), ...(leftovers.length > 0 ? { leftoversStopped: leftovers } : {}) });
    });
  });
}

// Tier 2: executes caller-supplied commands (the target's own test/lint/
// build command) through a filtered child environment. Every command in
// this call is bound to the SAME snapshotHash, captured once before the
// first command runs.
async function runTier2({ cd, commands, timeout, envMode, envPassthrough }, spawnOpts = {}) {
  const snapshotHash = await computeSnapshotHash(cd);
  const env = buildChildEnv({ envMode, envPassthrough, providerAllowlist: NETWORK_ENV_ALLOWLIST });
  const results = [];
  for (const command of commands) {
    const startedAt = new Date().toISOString();
    const startedAtMs = Date.now();
    const before = await contentState(cd);
    const result = await runWithTimeout(command, { cd, env, timeout }, spawnOpts);
    const after = await contentState(cd);
    results.push({
      command,
      startedAt,
      finishedAt: new Date().toISOString(),
      durationMs: Date.now() - startedAtMs,
      exitCode: result.code,
      timedOut: result.timedOut,
      timeoutS: timeout,
      ...(result.leftoversStopped ? { leftoversStopped: result.leftoversStopped } : {}),
      ...(result.leftoverGroupStopped ? { leftoverGroupStopped: true } : {}),
      ...(result.outputHeldOpen ? { outputHeldOpen: true } : {}),
      touchedFiles: diffInventories(before, after),
      stdout: result.stdout,
      stderr: result.stderr,
    });
  }
  const snapshotHashAfter = await computeSnapshotHash(cd);
  return { snapshotHash, snapshotHashAfter, targetChanged: snapshotHashAfter !== snapshotHash, results };
}

// Content hash of every file that differs from HEAD or is untracked under cd (git), or of every
// file (plain folder). Comparing two of these shows what a command wrote, including re-edits of
// an already-dirty file. Gitignored output is not covered.
async function contentState(cd) {
  if (!(await isGitRepo(cd))) return (await hashInventory(cd)).files;
  const [changed, untracked] = await gitOutAll([
    [...GIT_PLAIN, 'diff', ...DIFF_PLAIN, 'HEAD', '--no-renames', '--name-only', '--relative', '-z', '--', '.'],
    ['ls-files', '--others', '--exclude-standard', '-z'],
  ], cd);
  const listed = new Map([...gitNames(changed.stdout), ...gitNames(untracked.stdout)].filter((e) => !e.text.endsWith('/')).map((e) => [entryKey(e), e]));
  const state = {};
  for (const rel of [...listed.keys()].sort()) {
    try {
      state[rel] = await entrySha256(entryPath(cd, listed.get(rel)));
    } catch (err) {
      state[rel] = err.code === 'ENOENT' ? 'deleted' : `unreadable: ${err.code || err.message}`;
    }
  }
  return state;
}

const FETCH_TIMEOUT_MS = 120000;

async function gitLine(args, cwd) {
  const r = await runCapture('git', args, cwd);
  return r.code === 0 ? r.stdout.toString('utf8').trim() : null;
}

async function revCount(range, cwd) {
  const out = await gitLine(['rev-list', '--count', range], cwd);
  return out === null ? null : Number(out);
}

// No prompt and a hard time limit: an expired token must fail, not hang the review.
function gitFetch(cwd) {
  return new Promise((resolve) => {
    const env = { ...process.env, GIT_TERMINAL_PROMPT: '0', GCM_INTERACTIVE: 'never' };
    const child = spawn('git', ['fetch', '--quiet'], { windowsHide: true, cwd, env, shell: false, timeout: FETCH_TIMEOUT_MS });
    let stderr = '';
    child.stderr.on('data', (d) => { stderr += d.toString('utf8'); });
    child.on('error', (err) => resolve({ ok: false, error: err.message }));
    child.on('close', (code, signal) => {
      if (code === 0) resolve({ ok: true, error: null });
      else resolve({ ok: false, error: signal ? `killed by ${signal} after ${FETCH_TIMEOUT_MS / 1000} s` : stderr.trim() || `exit ${code}` });
    });
  });
}

// Branch, HEAD and how far HEAD is behind its upstream and origin/HEAD: raw git facts only.
async function repoFreshness(dir, { role, fetch = false }) {
  const abs = path.resolve(dir);
  try {
    if (!(await stat(abs)).isDirectory()) throw new Error('not a directory');
  } catch (err) {
    throw new RelayError(`--${role === 'cd' ? 'cd' : 'repo'} "${abs}" is not an accessible directory: ${err.message}`);
  }
  if (!(await isGitRepo(abs))) return { path: abs, role, gitRepo: false };
  const record = { path: abs, role, gitRepo: true, fetched: false };
  if (fetch) {
    const f = await gitFetch(abs);
    record.fetched = f.ok;
    if (!f.ok) record.fetchError = f.error;
  }
  const branch = await gitLine(['rev-parse', '--abbrev-ref', 'HEAD'], abs);
  record.branch = branch === 'HEAD' ? null : branch;
  record.head = await gitLine(['rev-parse', 'HEAD'], abs);
  record.headDate = await gitLine(['log', '-1', '--format=%cI', 'HEAD'], abs);
  const status = await gitLine(['status', '--porcelain', '--', '.'], abs);
  record.dirty = status === null ? null : status.length > 0;
  record.upstream = await gitLine(['rev-parse', '--abbrev-ref', '--symbolic-full-name', '@{upstream}'], abs);
  record.ahead = record.upstream ? await revCount('@{upstream}..HEAD', abs) : null;
  record.behind = record.upstream ? await revCount('HEAD..@{upstream}', abs) : null;
  record.defaultBranch = await gitLine(['symbolic-ref', '--quiet', '--short', 'refs/remotes/origin/HEAD'], abs);
  record.behindDefault = record.defaultBranch ? await revCount(`HEAD..${record.defaultBranch}`, abs) : null;
  const fetchHead = await gitLine(['rev-parse', '--git-path', 'FETCH_HEAD'], abs);
  record.lastFetchedAt = null;
  if (fetchHead) {
    try {
      record.lastFetchedAt = (await stat(path.resolve(abs, fetchHead))).mtime.toISOString();
    } catch {
      // Never fetched: no FETCH_HEAD file, lastFetchedAt stays null.
    }
  }
  return record;
}

const ARTIFACT_MAX_BYTES = 2 * 1024 * 1024;
const MAX_ARTIFACT_FILES = 50;
const ARTIFACT_READ_CONCURRENCY = 16;
const WALK_SKIP = new Set(['.git', 'node_modules']);

// A past run's findings file or findings.json inside a target makes its real claim IDs "target
// text", so the scan's target-derived exemption could pass a real leak of those IDs. Match real
// review output only: a seat header, a claim heading with a dash plus a Severity line, or a
// findings.json with both origins and final_state. The protocol's own schema example is skipped.
function looksLikeReviewOutput(text) {
  if (/^# Shared Review Protocol\b/.test(text)) return false;
  if (/^# Seat [AB] findings\b/m.test(text)) return true;
  if (/^#{2,3} [AB]\d+ [—–-] /m.test(text) && /^Severity: /m.test(text)) return true;
  return /"origins"\s*:\s*\[\s*"[AB]\d+"/.test(text) && /"final_state"\s*:/.test(text);
}

// Lazy, so the scan below can stop walking a large plain folder once it has enough hits.
async function* walkFileNames(root, rel = '') {
  for (const d of await readdir(path.join(root, rel), { withFileTypes: true })) {
    const relPath = rel ? path.join(rel, d.name) : d.name;
    if (d.isDirectory()) {
      if (!WALK_SKIP.has(d.name)) yield* walkFileNames(root, relPath);
    } else if (d.isFile()) {
      yield relPath;
    }
  }
}

async function listTargetFiles(dir) {
  if (await isGitRepo(dir)) {
    const r = await runCapture('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], dir);
    return r.stdout.toString('utf8').split('\0').filter((p) => p.length > 0 && !p.endsWith('/'))[Symbol.iterator]();
  }
  return walkFileNames(dir);
}

// Reads with bounded concurrency and stops listing and reading once MAX_ARTIFACT_FILES are found;
// capped:true then says the count is a lower bound.
async function findReviewArtifacts(dir, list = listTargetFiles) {
  const names = await list(dir);
  const found = [];
  let exhausted = false;
  // Workers take names one at a time from the shared iterator (git list or lazy folder walk).
  const take = async () => {
    const r = await names.next();
    if (r.done) exhausted = true;
    return r.done ? null : r.value;
  };
  const worker = async () => {
    while (!exhausted && found.length < MAX_ARTIFACT_FILES) {
      const rel = await take();
      if (rel === null) break;
      try {
        const full = path.join(dir, rel);
        const st = await stat(full);
        if (!st.isFile() || st.size > ARTIFACT_MAX_BYTES) continue;
        const text = await readFile(full, 'utf8');
        if (!text.includes('\0') && looksLikeReviewOutput(text)) found.push(rel.split(path.sep).join('/'));
      } catch {
        // Deleted or unreadable between listing and reading: nothing to report for it.
      }
    }
  };
  await Promise.all(Array.from({ length: ARTIFACT_READ_CONCURRENCY }, worker));
  // Stopped early with names left unread: the count is only a lower bound.
  const capped = !exhausted && !(await names.next()).done;
  if (typeof names.return === 'function') await names.return();
  return { count: found.length, files: [...found].sort().slice(0, MAX_ARTIFACT_FILES), capped };
}

// Each watch file goes to the most specific --cd/--repo that contains it; for that repo, counts the
// commits on its upstream and origin/HEAD (when behind) that touch the file.
async function watchUpstreamChanges(records, watchFiles) {
  const outside = [];
  for (const file of watchFiles) {
    const abs = path.resolve(file);
    // Compared through the real path (/tmp and /private/tmp, a linked checkout are one folder); the path given to git
    // keeps its case, which comparablePath folds on Windows.
    const owner = records
      .filter((r) => r.gitRepo && r.head && isInsidePath(abs, r.path) && comparablePath(abs) !== comparablePath(r.path))
      .map((r) => ({ r, rel: path.relative(realPath(r.path), realPath(abs)) }))
      .sort((a, b) => b.r.path.length - a.r.path.length)[0];
    if (!owner) {
      outside.push(abs);
      continue;
    }
    const { r, rel } = owner;
    r.watchedChangedUpstream ??= [];
    const gitRel = rel.split(path.sep).join('/');
    const refs = [];
    if (r.behind > 0) refs.push(r.upstream);
    if (r.behindDefault > 0 && r.defaultBranch !== r.upstream) refs.push(r.defaultBranch);
    for (const ref of refs) {
      const log = await gitLine(['log', '--format=%h', `HEAD..${ref}`, '--', gitRel], r.path);
      const commits = log ? log.split('\n').filter(Boolean).length : 0;
      if (commits > 0) {
        // The same change can reach HEAD through another merge: commits differ, content does not.
        const diff = await runCapture('git', ['diff', '--quiet', 'HEAD', ref, '--', gitRel], r.path);
        r.watchedChangedUpstream.push({ file: gitRel, ref, commits, contentDiffers: diff.code === 1 ? true : diff.code === 0 ? false : null });
      }
    }
  }
  return outside;
}

function freshnessWarnings(records) {
  const lines = [];
  for (const r of records) {
    if (r.reviewArtifactCount > 0) {
      lines.push(`preflight: WARNING: ${r.reviewArtifactCount}${r.reviewArtifactCountIsLowerBound ? '+' : ''} file(s) in ${r.path} ` +
        `hold review output with real claim IDs (seat headers, claim blocks or findings.json), e.g. ${r.reviewArtifactFiles[0]}`);
    }
    for (const w of r.watchedChangedUpstream ?? []) {
      if (w.contentDiffers === false) {
        lines.push(`preflight: note: ${w.file} in ${r.path} has ${w.commits} commit(s) on ${w.ref} not in HEAD, but its content is identical to HEAD`);
      } else {
        lines.push(`preflight: WARNING: ${w.file} in ${r.path} changed in ${w.commits} commit(s) on ${w.ref} not in HEAD and differs from HEAD`);
      }
    }
    if (r.behind > 0) lines.push(`preflight: WARNING: ${r.path} is ${r.behind} commit(s) behind ${r.upstream}`);
    if (r.behindDefault > 0 && r.defaultBranch !== r.upstream) {
      lines.push(`preflight: WARNING: ${r.path} is ${r.behindDefault} commit(s) behind ${r.defaultBranch}`);
    }
    if (r.fetchError) lines.push(`preflight: WARNING: git fetch failed in ${r.path}: ${r.fetchError}`);
  }
  return lines;
}

// Re-checks whether a previously-captured snapshotHash still matches the
// target's CURRENT state. A caller uses this before citing old Tier 2 (or
// Tier 1) evidence as current -- stale evidence must never be presented as
// describing content it no longer describes. Never mutates or interprets
// the evidence; only reports match/mismatch as a fact.
async function checkStale(cd, snapshotHash) {
  const current = await computeSnapshotHash(cd);
  return { stale: current !== snapshotHash, currentSnapshotHash: current };
}

// One stdout line for a run written to --out, so the hash and exit codes can be read without opening the JSON.
// "0 (152 passed)": the exit code, then the last summary line the command printed when the compact output kept one.
function commandOutcome(r) {
  const code = r.timedOut ? `timeout after ${r.timeoutS ?? '?'} s (raise with --timeout <seconds>, 0 = unlimited)` : r.exitCode;
  const line = Array.isArray(r.stdout?.summary) ? r.stdout.summary.at(-1) : null;
  return typeof line === 'string' && line.trim() !== '' ? `${code} (${line.trim().slice(0, 50)})` : String(code);
}

export function summaryLine(result, out) {
  const tiers = [['tier2', result.tier2], ...(result.tier2Repos ?? []).map((r) => [`tier2Repos ${r.path}`, r])]
    .filter(([, t]) => t)
    .map(([label, t]) => `${label}: ${t.results.length} command(s), exit ${t.results.map(commandOutcome).join(', ')}, targetChanged ${t.targetChanged}`);
  const changed = Array.isArray(result.tier1?.changedFiles) ? result.tier1.changedFiles : null;
  // A subfolder target's status paths start with its repository prefix ("sub/"); changedFiles are --cd relative.
  const prefix = result.tier1?.gitPrefix ?? '';
  const untracked = String(result.tier1?.status ?? '').split(/\r?\n/).filter((l) => l.startsWith('?? ')).map((l) => l.slice(3).trim())
    .map((u) => (prefix && u.replace(/^"/, '').startsWith(prefix) ? u.replace(/^("?)/, '$1').replace(prefix, '') : u));
  // git status shows a new folder as one "?? dir/" entry; the count is of files, like the changed-file count.
  // A name git quotes ("sp ace.txt") is compared without its quotes; an entry that still matches no file counts as one.
  const bare = untracked.map((u) => u.replace(/^"(.*)"$/, '$1'));
  const untrackedFiles = changed === null ? untracked.length : bare.reduce((n, u) => n + Math.max(1, changed.filter((f) => (u.endsWith('/') ? f.startsWith(u) : f === u)).length), 0);
  const more = untracked.length > 5 ? ', +' + (untracked.length - 5) + ' more' : '';
  const untrackedText = untracked.length > 0 ? ' (' + untrackedFiles + ' untracked: ' + untracked.slice(0, 5).join(', ') + more + ')' : '';
  const since = result.tier1?.base ? ' since ' + result.tier1.base.slice(0, 12) : '';
  const changedText = changed === null ? '' : '; ' + changed.length + ' changed file(s)' + since + untrackedText;
  return `preflight: wrote ${out}; snapshotHash ${result.snapshotHash}${changedText}${tiers.length > 0 ? `; ${tiers.join('; ')}` : '; no Tier 2 command'}`;
}

async function run(args) {
  assertNodeVersion();
  const cdAbs = path.resolve(args.cd);
  let cdStat;
  try {
    cdStat = await stat(cdAbs);
  } catch (err) {
    throw new RelayError(`--cd "${cdAbs}" does not exist or is not accessible: ${err.message}`);
  }
  if (!cdStat.isDirectory()) {
    throw new RelayError(`--cd "${cdAbs}" is not a directory`);
  }

  for (const { dir } of args.execIn ?? []) {
    const abs = path.resolve(dir);
    const st = await stat(abs).catch((err) => { throw new RelayError(`--exec-in "${abs}" does not exist or is not accessible: ${err.message}`); });
    if (!st.isDirectory()) throw new RelayError(`--exec-in "${abs}" is not a directory`);
  }
  const clearedLogs = args.compact ? await clearOwnLogs(args.logDir) : [];
  // The earlier --out file cites the logs just deleted; a rerun that is stopped before it writes must not leave it behind.
  if (clearedLogs.length > 0 && args.out) await rm(path.resolve(args.out), { force: true });
  // A plain folder is hashed file by file; do it once for Tier 1 and the snapshot hash.
  const inventory = (await isGitRepo(cdAbs)) ? null : await hashInventory(cdAbs);
  const tier1 = await runTier1(cdAbs, inventory, args.base ?? null);

  let snapshotHash = await computeSnapshotHash(cdAbs, inventory);
  let tier2 = null;
  if (args.exec.length > 0) {
    tier2 = await runTier2({
      cd: cdAbs,
      commands: args.exec,
      timeout: args.timeout,
      envMode: args.envMode,
      envPassthrough: args.envPassthrough,
    });
    // Tier 1 and Tier 2 are computed from the same pre-command git state in
    // a single invocation (Tier 1 runs, then Tier 2's own snapshotHash is
    // captured immediately before its first --exec command) -- both must
    // agree, since nothing in this process mutates the target between them.
    snapshotHash = tier2.snapshotHash;
    if (args.compact) tier2 = await compactTier2(tier2, args);
  }

  // Each --exec-in directory is its own target: own snapshotHash, own touchedFiles, own staleness check.
  const tier2Repos = [];
  const groups = new Map();
  for (const { dir, command } of args.execIn ?? []) {
    const abs = path.resolve(dir);
    if (!groups.has(abs)) groups.set(abs, []);
    groups.get(abs).push(command);
  }
  let logOffset = tier2?.results.length ?? 0;
  for (const [abs, commands] of groups) {
    let st;
    try {
      st = await stat(abs);
    } catch (err) {
      throw new RelayError(`--exec-in "${abs}" does not exist or is not accessible: ${err.message}`);
    }
    if (!st.isDirectory()) throw new RelayError(`--exec-in "${abs}" is not a directory`);
    let repoTier2 = await runTier2({ cd: abs, commands, timeout: args.timeout, envMode: args.envMode, envPassthrough: args.envPassthrough });
    if (args.compact) repoTier2 = await compactTier2(repoTier2, args, logOffset);
    logOffset += commands.length;
    tier2Repos.push({ path: abs, ...repoTier2 });
  }

  let execInChangedTarget = false;
  if (tier2Repos.length > 0) {
    const reviewedHash = tier2 ? tier2.snapshotHashAfter : snapshotHash;
    // main() prints the warning with the other notes (on stdout with --out).
    execInChangedTarget = (await computeSnapshotHash(cdAbs)) !== reviewedHash;
  }
  const repos = [await repoFreshness(cdAbs, { role: 'cd', fetch: args.fetch })];
  for (const repo of args.repos ?? []) repos.push(await repoFreshness(repo, { role: 'repo', fetch: args.fetch }));
  const outside = await watchUpstreamChanges(repos, args.watchFiles ?? []);
  for (const r of repos) {
    const artifacts = await findReviewArtifacts(r.path);
    if (artifacts.count > 0) {
      r.reviewArtifactCount = artifacts.count;
      r.reviewArtifactFiles = artifacts.files;
      if (artifacts.capped) r.reviewArtifactCountIsLowerBound = true;
    }
  }

  const result = { tier1: args.compact ? await compactTier1(tier1, args) : tier1, tier2, snapshotHash, repos };
  if (tier2Repos.length > 0) result.tier2Repos = tier2Repos;
  if (execInChangedTarget) result.execInChangedTarget = true;
  if (outside.length > 0) result.watchFilesOutsideRepos = outside;
  if ((args.sourceSnapshots ?? []).length > 0) result.sourceSnapshots = await recordSourceSnapshots(args.sourceSnapshots);
  if (clearedLogs.length > 0) result.clearedEarlierLogs = clearedLogs.sort();
  return result;
}

// A plain export (git archive) of another repository has no git metadata, so its origin is
// recorded as stated and its bytes are pinned by a content-hash inventory.
async function recordSourceSnapshots(snapshots) {
  const out = [];
  for (const s of snapshots) {
    const abs = path.resolve(s.dir);
    let st;
    try {
      st = await stat(abs);
    } catch (err) {
      throw new RelayError(`--source-snapshot folder "${abs}" does not exist or is not accessible: ${err.message}`);
    }
    if (!st.isDirectory()) throw new RelayError(`--source-snapshot "${abs}" is not a directory`);
    // Python caches left by an earlier test run are not source; they would change the hash with no source change.
    const inventory = await hashInventory(abs, { skipCaches: true });
    const rec = { path: abs, repo: s.repo, ref: s.ref, fileCount: Object.keys(inventory.files).length, snapshotHash: inventory.snapshotHash };
    if (inventory.skippedCaches.length > 0) {
      rec.skippedCacheCount = inventory.skippedCaches.length;
      rec.skippedCaches = inventory.skippedCaches.slice(0, 20);
    }
    out.push(rec);
  }
  return out;
}

const OWN_LOG_RE = /^(command-\d+\.std(out|err)\.log|tier1\.diff)$/;

// A rerun into the same --log-dir replaces this script's own earlier logs (a stale command-3 log
// from a longer earlier run would otherwise look like current evidence); other files stay.
async function clearOwnLogs(logDir) {
  const dir = path.resolve(logDir);
  let names = [];
  try {
    names = await readdir(dir);
  } catch (err) {
    if (err.code === 'ENOENT') return [];
    throw err;
  }
  const removed = names.filter((n) => OWN_LOG_RE.test(n));
  for (const n of removed) await rm(path.join(dir, n), { force: true });
  return removed;
}

// The Tier 1 diff can be as large as the whole change under review; seats read it from the log or git.
async function compactTier1(tier1, { logDir }) {
  if (!tier1.gitRepo) return tier1;
  const dir = path.resolve(logDir);
  await mkdir(dir, { recursive: true });
  const diffLog = path.join(dir, 'tier1.diff');
  await writeFile(diffLog, tier1.diff, 'utf8');
  const { diff, ...rest } = tier1;
  return {
    ...rest,
    diff: { bytes: Buffer.byteLength(diff, 'utf8'), sha256: sha256(Buffer.from(diff, 'utf8')), log: diffLog },
  };
}

function streamSummary(text, tailLines) {
  const lines = text.split(/\r?\n/);
  if (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
  const matches = lines.filter(isSignalLine);
  return {
    bytes: Buffer.byteLength(text, 'utf8'),
    sha256: sha256(Buffer.from(text, 'utf8')),
    lineCount: lines.length,
    tail: tailLines > 0 ? lines.slice(-tailLines) : [],
    summary: lines.filter((l) => SUMMARY_RE.test(l)).slice(-MAX_MATCH_LINES),
    matches: matches.slice(0, MAX_MATCH_LINES),
    matchesTruncated: matches.length > MAX_MATCH_LINES,
  };
}

// Full streams go to --log-dir; the JSON keeps only what a reader needs to judge and verify them.
async function compactTier2(tier2, { logDir, tail }, logOffset = 0) {
  const dir = path.resolve(logDir);
  await mkdir(dir, { recursive: true });
  const results = [];
  for (const [i, r] of tier2.results.entries()) {
    const stdoutLog = path.join(dir, `command-${logOffset + i + 1}.stdout.log`);
    const stderrLog = path.join(dir, `command-${logOffset + i + 1}.stderr.log`);
    await writeFile(stdoutLog, r.stdout, 'utf8');
    await writeFile(stderrLog, r.stderr, 'utf8');
    const { stdout, stderr, ...rest } = r;
    results.push({
      ...rest,
      stdout: { ...streamSummary(stdout, tail), log: stdoutLog },
      stderr: { ...streamSummary(stderr, tail), log: stderrLog },
    });
  }
  return { snapshotHash: tier2.snapshotHash, snapshotHashAfter: tier2.snapshotHashAfter, targetChanged: tier2.targetChanged, compact: true, results };
}

// Both families present and no usable --host is ambiguous; inherited env markers only add a hint to the error.
function resolveHost({ toolsClaudeCode = false, toolsCodex = false, hostFlag = null, interactive = false, env = process.env } = {}) {
  if (hostFlag !== null && hostFlag !== undefined && !HOSTS.includes(hostFlag)) {
    throw new RelayError(`--host must be one of ${HOSTS.join(', ')}, got "${hostFlag}"`);
  }
  const contradicts = (hostFlag === 'codex' && toolsClaudeCode && !toolsCodex) || (hostFlag === 'claude-code' && toolsCodex && !toolsClaudeCode);
  if (hostFlag && !contradicts) return hostFlag;
  if (toolsClaudeCode && !toolsCodex) return 'claude-code';
  if (toolsCodex && !toolsClaudeCode) return 'codex';
  if (interactive) return 'ambiguous';
  const hints = [env.CODEX_THREAD_ID ? 'CODEX_THREAD_ID is set' : null, env.CLAUDECODE ? 'CLAUDECODE is set' : null].filter(Boolean);
  const why = toolsClaudeCode && toolsCodex ? 'both a Claude Code and a Codex agent tool family are present' : 'no agent tool family was recognised';
  throw new RelayError(`the host is ambiguous (${why}); pass --host claude-code or --host codex${hints.length > 0 ? ` (hint only, never decisive: ${hints.join(', ')})` : ''}`);
}

