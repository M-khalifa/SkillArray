// The scripts use APIs from Node 22. An older Node otherwise fails somewhere later with an error about a missing
// function, which reads as a bug in the review rather than as a version problem.
const MIN_NODE_MAJOR = 22;
function assertNodeVersion(version = process.versions.node) {
  const major = Number(String(version).split('.')[0]);
  if (!Number.isInteger(major) || major < MIN_NODE_MAJOR) {
    throw new RelayError(`Node.js ${MIN_NODE_MAJOR} or newer is required (this is ${version}); install a current Node.js and rerun`);
  }
}

